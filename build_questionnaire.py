PURPLE = RGBColor(123, 63, 228)
DARK = RGBColor(30, 30, 35)
GRAY = RGBColor(100, 100, 110)

def add_header(title):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(16)
    run = p.add_run(title)
    run.font.name = "Arial"
    run.font.size = Pt(16)
    run.font.bold = True
    run.font.color.rgb = PURPLE

def add_q(q_text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.keep_with_next = True
    run = p.add_run(q_text)
    run.font.name = "Arial"
    run.font.size = Pt(11.5)
    run.font.bold = True
    run.font.color.rgb = DARK

def add_a(a_text, italic=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(a_text)
    run.font.name = "Arial"
    run.font.size = Pt(11)
    run.font.italic = italic
    run.font.color.rgb = DARK

def add_bullet(b_title, b_desc):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after = Pt(3)
    run_t = p.add_run(b_title + (" — " if b_desc else ""))
    run_t.font.name = "Arial"
    run_t.font.size = Pt(10.5)
    run_t.font.bold = True
    run_t.font.color.rgb = DARK
    if b_desc:
        run_d = p.add_run(b_desc)
        run_d.font.name = "Arial"
        run_d.font.size = Pt(10.5)
        run_d.font.color.rgb = DARK

